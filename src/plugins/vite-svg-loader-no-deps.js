import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, join, basename, extname } from 'path';

export default function svgSpritePlugin(userOptions = {}) {
  const defaultOptions = {
    iconsDir: 'src/icons', // SVG图标目录
    spriteId: 'svg-sprite', // 雪碧图容器ID
    prefix: 'icon', // 图标名前缀
    outputFile: 'sprite.svg', // 输出文件名
    defaultViewBox: '0 0 24 24' // 默认viewBox
  };

  const options = { ...defaultOptions, ...userOptions };

  // 生成symbol元素
  const createSymbol = (content, file) => {
    const fileName = basename(file, extname(file));
    const id = `${options.prefix}-${fileName}`;

    // 提取viewBox
    const viewBoxMatch = content.match(/viewBox=["']([^"']+)["']/i);
    const viewBox = viewBoxMatch ? viewBoxMatch[1] : options.defaultViewBox;

    // 提取有效内容（移除svg标签）
    const innerContent = content
      .replace(/<svg[^>]*>/i, '')
      .replace(/<\/svg>/i, '')
      .trim();

    return `<symbol id="${id}" viewBox="${viewBox}">${innerContent}</symbol>`;
  };

  // 生成雪碧图
  const generateSprite = () => {
    try {
      const iconsPath = resolve(process.cwd(), options.iconsDir);
      if (!existsSync(iconsPath)) {
        console.warn(`[svg-sprite] 图标目录不存在: ${iconsPath}`);
        return '';
      }

      const files = readdirSync(iconsPath);
      const symbols = [];

      files.forEach((file) => {
        if (extname(file) !== '.svg') return;

        const filePath = join(iconsPath, file);
        const content = readFileSync(filePath, 'utf-8');
        symbols.push(createSymbol(content, file));
      });

      return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" style="display: none">
  <!-- Generated by vite-plugin-svg-sprite -->
  ${symbols.join('\n  ')}
</svg>`;
    } catch (error) {
      console.error('[svg-sprite] 生成雪碧图失败:', error);
      return '';
    }
  };

  return {
    name: 'vite-plugin-svg-sprite',

    // 开发服务器配置
    configureServer(server) {
      const iconsPath = resolve(options.iconsDir);
      server.watcher.add(iconsPath);
      server.watcher.on('all', (event, path) => {
        if (path.includes(options.iconsDir) && event !== 'change') {
          this.buildStart();
          setTimeout(() => server.ws.send({ type: 'full-reload' }), 100);
        }
      });
    },

    // 构建时生成
    buildStart() {
      const spriteContent = generateSprite();
      const outputPath = resolve(process.cwd(), 'public', options.outputFile);
      writeFileSync(outputPath, spriteContent)
      console.log(`[svg-sprite] 雪碧图已生成: ${outputPath}`);
    },

    // 注入HTML
    transformIndexHtml(html) {
      return [
        {
          tag: 'div',
          injectTo: 'body-prepend',
          attrs: {
            'aria-hidden': 'true',
            style: 'display: none;'
          },
          children: readFileSync(resolve(process.cwd(), 'public', options.outputFile), 'utf-8')
        }
      ];
    }
  };
}
